import type React from 'react'
import { VisualDemoFrame } from './VisualDemoHost'

type FlowStep = { label: string; detail: string; check: string }
type FlowConfig = { goal: string; steps: FlowStep[] }

function ConceptFlowDemo({ config }: { config: FlowConfig }) {
  return (
    <VisualDemoFrame
      goal={config.goal}
      controls={[
        {
          name: 'stage',
          label: 'Шаг',
          type: 'slider',
          min: 0,
          max: config.steps.length - 1,
          step: 1,
        },
      ]}
      defaults={{ stage: 0 }}
    >
      {(state, setParam) => {
        const active = Math.min(config.steps.length - 1, Number(state.stage))
        const step = config.steps[active]
        return (
          <div>
            <div className="overflow-x-auto p-4 pb-2">
              <div className="flex min-w-[560px] items-stretch gap-2">
                {config.steps.map((item, index) => (
                  <div key={item.label} className="contents">
                    <button
                      type="button"
                      onClick={() => setParam('stage', index)}
                      aria-pressed={index === active}
                      className="min-h-20 flex-1 rounded-xl border px-3 py-2 text-center text-xs font-semibold transition"
                      style={{
                        borderColor:
                          index === active ? 'var(--dp-accent)' : 'var(--dp-border-subtle)',
                        background:
                          index === active
                            ? 'var(--dp-accent-subtle)'
                            : index < active
                              ? 'var(--dp-success-subtle)'
                              : 'var(--dp-surface)',
                        color: index === active ? 'var(--dp-accent)' : 'var(--dp-text-secondary)',
                        opacity: index > active ? 0.62 : 1,
                      }}
                    >
                      <span className="mb-1 block font-mono text-[10px] opacity-60">
                        {index + 1}
                      </span>
                      {item.label}
                    </button>
                    {index < config.steps.length - 1 && (
                      <span className="self-center" style={{ color: 'var(--dp-text-muted)' }}>
                        →
                      </span>
                    )}
                  </div>
                ))}
              </div>
            </div>
            <div className="grid gap-3 p-4 pt-2 sm:grid-cols-[1.5fr_1fr]">
              <div className="rounded-xl p-4" style={{ background: 'var(--dp-surface)' }}>
                <p className="text-xs font-semibold" style={{ color: 'var(--dp-accent)' }}>
                  Шаг {active + 1}: {step.label}
                </p>
                <p
                  className="mt-2 text-sm leading-relaxed"
                  style={{ color: 'var(--dp-text-secondary)' }}
                >
                  {step.detail}
                </p>
              </div>
              <div className="rounded-xl p-4" style={{ background: 'var(--dp-warning-subtle)' }}>
                <p
                  className="text-[10px] font-bold uppercase tracking-wider"
                  style={{ color: 'var(--dp-warning)' }}
                >
                  Контрольный вопрос
                </p>
                <p
                  className="mt-2 text-xs leading-relaxed"
                  style={{ color: 'var(--dp-text-secondary)' }}
                >
                  {step.check}
                </p>
              </div>
            </div>
          </div>
        )
      }}
    </VisualDemoFrame>
  )
}

